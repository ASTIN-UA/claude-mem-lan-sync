package cli

import (
	"fmt"
	"strings"
)

// windowsTaskName is the Scheduled Task that runs the hub on Windows.
const windowsTaskName = "cmemlan-hub"

// psQuote renders a PowerShell single-quoted string literal.
func psQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// windowsArgQuote quotes one argument for a Windows command line, the way the
// Task Scheduler hands it to the process.
func windowsArgQuote(s string) string {
	if s != "" && !strings.ContainsAny(s, " \t\"") {
		return s
	}
	return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
}

// windowsTaskScript renders the PowerShell that registers the hub as a
// Scheduled Task (issue #8).
//
// The shape is what has run the hub reliably on Windows 11:
//
//   - S4U logon: the hub runs with no console window at all and the Task
//     Scheduler supervises the process itself, so RestartCount works. An
//     Interactive task would open a console window for this console binary,
//     and a hidden launcher (wscript) exits at once, leaving nothing to
//     restart. S4U registration needs an elevated shell, so the script checks.
//   - an at-logon trigger delayed one minute, so a bind to a fixed LAN address
//     does not race DHCP or the network stack;
//   - no execution time limit (the default stops a task after three days) and
//     a restart every minute, five times, after a crash.
//
// The data directory is written in explicitly, like the systemd unit: a task
// that resolves a different directory than a manual `serve` gives the user an
// empty hub that looks like it lost every memory.
func windowsTaskScript(exe, dataDir, bind, allowCIDR string) string {
	args := []string{"serve", "--data-dir", windowsArgQuote(dataDir), "--bind", windowsArgQuote(bind)}
	if allowCIDR != "" {
		args = append(args, "--allow-cidr", windowsArgQuote(allowCIDR))
	}
	var b strings.Builder
	fmt.Fprintf(&b, `# Registers the %[1]s scheduled task: cmemlan serve in the background (S4U).
# Run from an elevated PowerShell. Generated by cmemlan serve --install-service.
$ErrorActionPreference = 'Stop'

$exe  = %[2]s
$args = %[3]s
$user = "$env:USERDOMAIN\$env:USERNAME"

$isAdmin = ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()
  ).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) { throw 'Registering an S4U task needs an elevated (Administrator) PowerShell.' }

$a = New-ScheduledTaskAction -Execute $exe -Argument $args -WorkingDirectory (Split-Path $exe)
$t = New-ScheduledTaskTrigger -AtLogOn -User $user
$t.Delay = 'PT1M'
$p = New-ScheduledTaskPrincipal -UserId $user -LogonType S4U -RunLevel Limited
$s = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `+"`"+`
       -StartWhenAvailable -RestartCount 5 -RestartInterval (New-TimeSpan -Minutes 1) `+"`"+`
       -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew -Hidden

if (Get-ScheduledTask -TaskName %[4]s -ErrorAction SilentlyContinue) {
  Stop-ScheduledTask -TaskName %[4]s
}
Register-ScheduledTask -TaskName %[4]s -Action $a -Trigger $t -Principal $p -Settings $s `+"`"+`
  -Description 'claude-mem LAN sync hub (cmemlan serve), background S4U.' -Force | Out-Null
Start-ScheduledTask -TaskName %[4]s
Write-Output 'task %[1]s registered and started'
`, windowsTaskName, psQuote(exe), psQuote(strings.Join(args, " ")), psQuote(windowsTaskName))
	return b.String()
}

// windowsTaskRemoveScript stops and removes the task. The hub's data directory
// is never touched.
func windowsTaskRemoveScript() string {
	return fmt.Sprintf(`$ErrorActionPreference = 'Stop'
if (Get-ScheduledTask -TaskName %[1]s -ErrorAction SilentlyContinue) {
  Stop-ScheduledTask -TaskName %[1]s
  Unregister-ScheduledTask -TaskName %[1]s -Confirm:$false
  Write-Output 'task removed'
} else {
  Write-Output 'no such task'
}
`, psQuote(windowsTaskName))
}
